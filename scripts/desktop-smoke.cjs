// Real Electron integration check. Native dialogs are redirected into a temporary job.
const {app,BrowserWindow,dialog}=require('electron');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
let temp,win;
const delay=ms=>new Promise(r=>setTimeout(r,ms));
async function waitFor(fn,label){for(let i=0;i<150;i++){if(await fn())return;await delay(100);}throw new Error(`Timed out: ${label}`);}
const js=code=>win.webContents.executeJavaScript(code);
const clickText=text=>js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);
app.on('browser-window-created',(_e,w)=>{
  win=w;
  w.webContents.on('console-message',(_e,_level,message)=>{if(/Error|failed/i.test(message))console.error('renderer:',message);});
  w.webContents.once('did-finish-load',async()=>{
    try{
      temp=await fs.mkdtemp(path.join(os.tmpdir(),'bdl-desktop-'));
      const {run}=await import('../electron/project.js');
      const ffmpeg=(await import('ffmpeg-static')).default;
      const video=path.join(temp,'demo.mp4');
      await run(ffmpeg,['-v','error','-f','lavfi','-i','testsrc2=size=640x360:rate=24','-f','lavfi','-i','sine=frequency=440:sample_rate=44100','-t','4','-c:v','libx264','-c:a','aac',video]);
      const contentPath=path.join(temp,'demo_behavior_labels');
      dialog.showOpenDialog=async(_win,options)=>({canceled:false,filePaths:[options.properties.includes('openDirectory')?temp:options.filters[0].extensions.includes('json')?path.join(contentPath,'demo_labels.job.json'):video]});
      dialog.showSaveDialog=async()=>{throw new Error('Opening a video should only ask for the parent folder.');};
      await clickText('Start with a video');
      await waitFor(()=>js(`!!document.querySelector('.behavior-lane')&&!document.querySelector('.modal-backdrop')`),'open video');
      assert.equal(await js(`document.querySelectorAll('.behavior-lane').length`),10);
      assert.ok((await fs.stat(path.join(contentPath,'frames','frames.json'))).isFile());
      assert.ok((await fs.stat(path.join(contentPath,'demo_labels.job.json'))).isFile());
      assert.ok((await fs.stat(path.join(contentPath,'demo_labels.pkl'))).isFile());
      await waitFor(()=>js(`document.querySelector('video').readyState>=2`),'playback ready');
      assert.equal(await js(`document.querySelector('video').videoWidth`),640);
      assert.equal(await js(`document.querySelector('.exact-frame').naturalWidth`),640);
      assert.equal(await js(`document.querySelector('video').muted`),true);
      await js(`document.querySelector('[aria-label="Unmute video"]').click()`);
      await waitFor(()=>js(`!document.querySelector('video').muted`),'unmute');
      await js(`document.querySelector('[aria-label="Mute video"]').click()`);
      await waitFor(()=>js(`document.querySelector('video').muted`),'mute');
      await clickText('Add label');
      await waitFor(()=>js(`document.querySelectorAll('.label-clip').length===1`),'add label');
      await waitFor(()=>js(`document.querySelector('.save-status').textContent==='All changes saved'`),'autosave');
      let labels=(await import('../electron/pickle.js')).decodeLabels(await fs.readFile(path.join(contentPath,'demo_labels.pkl')));
      assert.deepEqual(labels.get(0),['sit']);assert.deepEqual(labels.get(24),[]);
      // Drag an empty paw lane to layer a second behavior.
      await js(`(()=>{const el=document.querySelector('[data-behavior="paw"]'),r=el.getBoundingClientRect();el.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,clientX:r.left+70,clientY:r.top+14}));window.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,clientX:r.left+190,clientY:r.top+14}));window.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:r.left+190,clientY:r.top+14}));})()`);
      await waitFor(()=>js(`document.querySelectorAll('.label-clip').length===2`),'draw label');
      await js(`document.querySelector('[aria-label="Undo"]').click()`);
      await waitFor(()=>js(`document.querySelectorAll('.label-clip').length===1`),'undo');
      await js(`document.querySelector('[aria-label="Redo"]').click()`);
      await waitFor(()=>js(`document.querySelectorAll('.label-clip').length===2`),'redo');
      // Move and trim the sit range with real renderer pointer events.
      await js(`(()=>{const el=document.querySelector('[data-behavior="sit"] .label-clip'),r=el.getBoundingClientRect();el.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,clientX:r.left+20,clientY:r.top+10}));window.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,clientX:r.left+70,clientY:r.top+10}));window.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:r.left+70,clientY:r.top+10}));})()`);
      await waitFor(()=>js(`Number(document.querySelector('[aria-label="Start frame"]').value)>0`),'move clip');
      const before=await js(`Number(document.querySelector('[aria-label="End frame exclusive"]').value)`);
      await js(`(()=>{const el=document.querySelector('[data-behavior="sit"] .trim-handle.right'),r=el.getBoundingClientRect();el.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,clientX:r.left+2,clientY:r.top+10}));window.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,clientX:r.left+42,clientY:r.top+10}));window.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:r.left+42,clientY:r.top+10}));})()`);
      await waitFor(()=>js(`Number(document.querySelector('[aria-label="End frame exclusive"]').value)>${before}`),'trim clip');
      const stepFrom=await js(`Number(document.querySelector('.scrubber').value)`);
      await js(`document.querySelector('[aria-label="Next frame"]').click()`);
      await waitFor(()=>js(`Number(document.querySelector('.scrubber').value)===${stepFrom+1}`),'step');
      await js(`document.querySelector('[aria-label="Play"]').click()`);
      await delay(500);
      assert.ok(await js(`Number(document.querySelector('.scrubber').value)>1`));
      await js(`document.querySelector('[aria-label="Pause"]').click()`);
      const originalClipWidth=await js(`document.querySelector('.label-clip').getBoundingClientRect().width`);
      const originalPlayheadX=await js(`document.querySelector('.playhead').getBoundingClientRect().left`);
      const originalBoundaries=await js(`Array.from(document.querySelectorAll('.label-clip')).map(el=>el.getAttribute('aria-label'))`);
      await js(`document.querySelector('[aria-label="Zoom timeline in"]').click()`);
      await waitFor(()=>js(`document.querySelector('.label-clip').getBoundingClientRect().width>${originalClipWidth}`),'time zoom in');
      assert.ok(Math.abs(await js(`document.querySelector('.playhead').getBoundingClientRect().left`)-originalPlayheadX)<2,'zoom preserves playhead position');
      assert.ok(await js(`document.querySelector('.timeline-scroll').scrollWidth>document.querySelector('.timeline-scroll').clientWidth`));
      assert.deepEqual(await js(`Array.from(document.querySelectorAll('.label-clip')).map(el=>el.getAttribute('aria-label'))`),originalBoundaries);
      const zoomedWidth=await js(`document.querySelector('.label-clip').getBoundingClientRect().width`);
      await js(`document.querySelector('[aria-label="Zoom timeline out"]').click()`);
      await waitFor(()=>js(`document.querySelector('.label-clip').getBoundingClientRect().width<${zoomedWidth}`),'time zoom out');
      await js(`document.querySelector('[aria-label="Zoom timeline in"]').click()`);
      await clickText('Fit');
      await waitFor(()=>js(`Number(document.querySelector('[aria-label="Timeline zoom"]').value)===0`),'fit timeline');
      assert.equal(await js(`document.querySelector('.timeline-scroll').scrollLeft`),0);
      await js(`(()=>{const el=document.querySelector('[aria-label="Track height"]');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(el,'68');el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
      await waitFor(()=>js(`document.querySelector('.timeline-scroll').scrollHeight>document.querySelector('.timeline-scroll').clientHeight`),'vertical overflow');
      await js(`document.querySelector('.timeline-scroll').scrollTop=500`);
      assert.ok(await js(`document.querySelector('.timeline-scroll').scrollTop>0`));
      await js(`document.querySelector('.timeline-scroll').scrollTop=0`);
      assert.equal(await js(`document.querySelector('[aria-label="Track height"]').value`),'68');
      win.setSize(1000,700);
      await delay(300);
      assert.equal(await js(`getComputedStyle(document.querySelector('video')).objectFit`),'contain');
      assert.ok(await js(`document.querySelector('.video-stage').clientHeight>100`));
      assert.ok(await js(`document.querySelector('.timeline-scroll').scrollHeight>document.querySelector('.timeline-scroll').clientHeight`));
      win.setSize(1500,950);
      await delay(1200);
      await fs.writeFile(path.join(temp,'editor.png'),(await win.webContents.capturePage()).toPNG());
      const saved=await fs.readFile(path.join(contentPath,'demo_labels.pkl'));
      await clickText('Resume job');
      await waitFor(()=>js(`!document.querySelector('.modal-backdrop')&&document.querySelectorAll('.label-clip').length===2`),'resume');
      assert.deepEqual(await fs.readFile(path.join(contentPath,'demo_labels.pkl')),saved);
      assert.equal(await js(`document.querySelector('video').muted`),true);
      assert.equal(await js(`document.querySelector('[role="alert"]')?.textContent||''`),'');
      console.log(JSON.stringify({ok:true,screenshot:path.join(temp,'editor.png'),checks:['open video','video decoding','10 tracks','add','draw','move','trim','undo','redo','frame step','playback','mute toggle and default','time zoom in/out','zoom anchor','vertical scroll','autosave','resume']}));
      app.exit(0);
    }catch(e){console.error(e);console.error('artifacts:',temp);if(win)await fs.writeFile(path.join(temp||os.tmpdir(),'failure.png'),(await win.webContents.capturePage()).toPNG());app.exit(1);}
  });
});
import('../electron/main.js');
